// Writes public/js/icons.js with the Lucide icons the app uses (run after changing the list:
// node scripts/build-icons.mjs). The output is committed, so the app itself needs no build step.
import fs from 'node:fs';

const ICONS = [
  'mic', 'circle-stop', 'radio-tower', 'audio-lines', 'settings', 'users', 'library', 'folder-lock', 'file-text',
  'presentation', 'file', 'upload', 'sun', 'moon', 'monitor', 'log-out', 'copy', 'trash-2', 'search', 'plus', 'minus',
  'x', 'check', 'chevron-down', 'chevron-right', 'sparkles', 'circle-help', 'pencil', 'external-link', 'folder-input',
  'key-round', 'user-plus', 'shield-check', 'menu', 'panel-left', 'arrow-down', 'message-square-text', 'info',
  'triangle-alert', 'circle-check', 'loader-circle', 'book-open', 'briefcase', 'wallet', 'user-round', 'lock',
  'type', 'send', 'eraser', 'headphones', 'cloud-upload', 'folder', 'layers', 'bot', 'gauge', 'eye', 'log-in',
  'picture-in-picture-2', 'chevron-left', 'captions',
  'refresh-cw', 'square', 'arrow-up', 'download', 'list', 'ellipsis', 'messages-square', 'quote', 'panel-right-close', 'text-search',
  'sliders-horizontal', 'pin', 'pin-off', 'keyboard', 'corner-down-left', 'mic-off', 'graduation-cap', 'volume-x', 'volume-2', 'flag',
];

const out = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(new URL(`../node_modules/lucide-static/icons/${name}.svg`, import.meta.url), 'utf8');
  out[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(new URL('../public/js/icons.js', import.meta.url),
  `// Generated by scripts/build-icons.mjs from lucide-static (ISC licence). Do not edit by hand.\nexport const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`Wrote ${ICONS.length} icons`);
